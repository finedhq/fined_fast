"""Write the WinterArc day cards as one SQL file to run in the Supabase SQL editor.

    python3 fined_backend/scripts/winterarc/sql.py [out_file]

Each card is validated exactly as the admin does on save (card_data.py), and
the stored card_data is the validated dict, so the rows match an admin import.

The SQL is safe to re-run:
  - day n is the module with order_index n in the 'winterarc' course; a
    missing module is created as a draft (an admin still publishes it);
  - a card whose slug already exists is updated in place, so it keeps its
    card_id and any answers recorded against it; other cards are inserted;
  - nothing is deleted.
"""
import importlib
import importlib.util
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
spec = importlib.util.spec_from_file_location("card_data", HERE.parents[1] / "app" / "models" / "card_data.py")
card_data = importlib.util.module_from_spec(spec)
spec.loader.exec_module(card_data)

from build import DAYS  # noqa: E402

TAG = "$wa_json$"


def lit(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def day_sql(day: int, cards: list) -> str:
    title = cards[0]["title"]  # the hero title, e.g. "Day 8: Introduction to Investing"
    out = [
        f"-- ---------------- Day {day}: {len(cards)} cards ----------------",
        "INSERT INTO public.modules (course_id, title, description, order_index, slug, status)",
        f"SELECT c.id, {lit(title)}, '', {day}, {lit(f'winterarc-day-{day:02d}')}, 'draft'",
        "FROM public.courses c",
        "WHERE c.slug = 'winterarc'",
        f"  AND NOT EXISTS (SELECT 1 FROM public.modules m WHERE m.course_id = c.id AND m.order_index = {day});",
        "",
    ]
    for c in cards:
        data = card_data.validate_card_data(c["card_type"], {**c["card_data"], "card_type": c["card_type"]})
        body = json.dumps(data, ensure_ascii=False)
        assert TAG not in body
        out += [
            "WITH m AS (",
            "  SELECT m.id FROM public.modules m JOIN public.courses c ON c.id = m.course_id",
            f"  WHERE c.slug = 'winterarc' AND m.order_index = {day} ORDER BY m.id LIMIT 1",
            "), d AS (",
            f"  SELECT {lit(c['slug'])}::text AS slug, {c['order_index']}::int AS order_index, {lit(c['card_type'])}::text AS card_template,",
            f"         {lit(c['title'])}::text AS title, {TAG}{body}{TAG}::jsonb AS card_data",
            "), upd AS (",
            "  UPDATE public.cards k SET module_id = m.id, order_index = d.order_index, card_template = d.card_template,",
            "         title = d.title, card_data = d.card_data",
            "  FROM d, m WHERE k.slug = d.slug RETURNING k.card_id",
            ")",
            "INSERT INTO public.cards (module_id, order_index, card_template, title, slug, card_data)",
            "SELECT m.id, d.order_index, d.card_template, d.title, d.slug, d.card_data FROM d, m",
            "WHERE NOT EXISTS (SELECT 1 FROM upd) AND NOT EXISTS (SELECT 1 FROM public.cards k WHERE k.slug = d.slug);",
            "",
        ]
    return "\n".join(out)


def main(out_file: pathlib.Path) -> None:
    days = []
    for name in DAYS:
        mod = importlib.import_module(name)
        days.append((int(name[3:]), mod.CARDS["cards"]))
    first, last = days[0][0], days[-1][0]
    head = f"""-- ==========================================================
-- WinterArc Days {first} to {last}: modules and cards
-- Generated by fined_backend/scripts/winterarc/sql.py. Do not edit by hand.
--
-- Run in the Supabase SQL editor: PRACTICE database first, then live.
-- Safe to re-run. Nothing is deleted.
--   * Day n is the module with order_index n in the 'winterarc' course.
--     A missing module is created as a DRAFT: publish it in the admin.
--   * A card whose slug already exists is updated in place (it keeps its
--     card_id and any answers); every other card is inserted.
-- If the 'winterarc' course is missing, nothing is written.
-- ==========================================================

BEGIN;

"""
    check = f"""
-- ---------------- Check ----------------
-- Expect one row per day: 8 cards, 3 quizzes. extra_cards > 0 means the module
-- also holds cards this file does not know about (for example a placeholder).
SELECT m.order_index AS day, m.title, m.status,
       count(k.*) AS cards,
       count(k.*) FILTER (WHERE k.card_template = 'quiz') AS quizzes,
       count(k.*) FILTER (WHERE k.slug NOT LIKE 'wa-d' || lpad(m.order_index::text, 2, '0') || '-%') AS extra_cards
FROM public.modules m
JOIN public.courses c ON c.id = m.course_id AND c.slug = 'winterarc'
LEFT JOIN public.cards k ON k.module_id = m.id
WHERE m.order_index BETWEEN {first} AND {last}
GROUP BY m.order_index, m.title, m.status
ORDER BY m.order_index;
"""
    sql = head + "\n".join(day_sql(d, cs) for d, cs in days) + "\nCOMMIT;\n" + check
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(sql)
    print(f"wrote {out_file} ({sum(len(cs) for _, cs in days)} cards, days {first}-{last})")


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "out" / "winterarc_days.sql")
