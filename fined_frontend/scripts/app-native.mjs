// What the installed Android app (the "native shell") contains, as opposed to the web code that live
// updates can replace. Live updates must never send web code that needs native pieces an installed
// app doesn't have (e.g. a new Capacitor plugin), so we fingerprint the native side and keep a
// record of it in app-native.json:
//   minVersionCode  - oldest Play Store build (versionCode) that can run today's web code
//   fingerprint     - hash of everything native: Capacitor plugins + versions, capacitor.config.json, android/
// scripts/build-app-update.mjs refuses to publish when the fingerprint no longer matches.
// After a native change ships to the Play Store, run `npm run app:native-bump`.
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const recordPath = join(root, 'app-native.json');

// The files under android/ that define the native shell. Only these are hashed, so stray local
// files (Android Studio settings, build output) can't make a laptop and the build server disagree.
const ANDROID_FILES = [
  'build.gradle',
  'settings.gradle',
  'variables.gradle',
  'gradle.properties',
  'gradle/wrapper/gradle-wrapper.properties',
  'app/build.gradle',
  'app/proguard-rules.pro',
];
const ANDROID_DIRS = ['app/src/main'];
// Inside those folders: generated by `cap sync`, so not part of the fingerprint.
const ANDROID_SKIP = [/^app\/src\/main\/assets\//, /^app\/src\/main\/res\/xml\/config\.xml$/];

function walk(dir, base, out) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const rel = relative(base, full).split(sep).join('/');
    if (ANDROID_SKIP.some((re) => re.test(rel) || re.test(`${rel}/`))) continue;
    if (statSync(full).isDirectory()) walk(full, base, out);
    else out.push(rel);
  }
  return out;
}

function androidFiles(androidDir) {
  const files = ANDROID_FILES.filter((rel) => existsSync(join(androidDir, rel)));
  for (const dir of ANDROID_DIRS) walk(join(androidDir, dir), androidDir, files);
  return files;
}

// Text files are hashed with Windows line endings turned into Unix ones, so a checkout on Windows
// and the Linux build server give the same fingerprint.
const TEXT = /\.(gradle|xml|java|kt|properties|json|pro|txt|md|bat)$|(^|\/)gradlew$/;
function fileBytes(path) {
  const buf = readFileSync(path);
  return TEXT.test(path) ? Buffer.from(buf.toString('utf8').replace(/\r\n/g, '\n')) : buf;
}

export function nativePlugins() {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const deps = pkg.dependencies || {};
  return Object.fromEntries(
    Object.keys(deps)
      .filter((name) => /^@capacitor\/|^@capgo\/|^@capacitor-/.test(name) && name !== '@capacitor/cli')
      .sort()
      .map((name) => [name, deps[name]]),
  );
}

export function nativeFingerprint() {
  const hash = createHash('sha256');
  hash.update(JSON.stringify(nativePlugins()));
  hash.update(fileBytes(join(root, 'capacitor.config.json')));
  const androidDir = join(root, 'android');
  for (const rel of androidFiles(androidDir).sort()) {
    hash.update(`\n${rel}\n`);
    hash.update(fileBytes(join(androidDir, rel)));
  }
  return hash.digest('hex');
}

export function androidVersionCode() {
  const gradle = readFileSync(join(root, 'android', 'app', 'build.gradle'), 'utf8');
  const match = gradle.match(/versionCode\s+(\d+)/);
  if (!match) throw new Error('versionCode not found in android/app/build.gradle');
  return Number(match[1]);
}

export function readRecord() {
  return JSON.parse(readFileSync(recordPath, 'utf8'));
}
